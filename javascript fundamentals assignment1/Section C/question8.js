//Number Comparison Logic
let scoreA = 75;
let scoreB = 82;

if (scoreA > scoreB) {
    console.log(`scoreA (${scoreA}) is greater than scoreB (${scoreB}).`);
} else if (scoreA < scoreB) {
    console.log(`scoreA (${scoreA}) is less than scoreB (${scoreB}).`);
} else {
    console.log(`scoreA (${scoreA}) is equal to scoreB (${scoreB}).`);
}
